fn command(kind: &str, label: &str, command: &str) -> ProjectCommandSpec {
    ProjectCommandSpec {
        kind: kind.to_string(),
        label: label.to_string(),
        command: command.to_string(),
    }
}

fn step(program: &'static str, args: &'static [&'static str]) -> CommandStep {
    CommandStep { program, args }
}

fn normalize_project_name(value: &str) -> Result<String, String> {
    let mut name = value.trim().to_lowercase();
    name = name
        .chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || ch == '-' || ch == '_' {
                ch
            } else if ch.is_whitespace() {
                '-'
            } else {
                '-'
            }
        })
        .collect::<String>();
    while name.contains("--") {
        name = name.replace("--", "-");
    }
    name = name.trim_matches('-').to_string();
    if name.is_empty() {
        return Err("Project name is required.".to_string());
    }
    if name.len() > 80 {
        return Err("Project name is too long. Max length: 80.".to_string());
    }
    Ok(name)
}

fn resolve_new_project_path(workspace_root: &Path, relative_path: &str) -> Result<PathBuf, String> {
    let path = normalize_relative_path(relative_path)?;
    Ok(workspace_root.join(path))
}

fn resolve_existing_project_path(workspace_root: &Path, path: &str) -> Result<PathBuf, String> {
    let path = normalize_relative_path(path)?;
    let full = workspace_root.join(path);
    if !full.is_dir() {
        return Err("Project directory does not exist.".to_string());
    }
    Ok(full)
}

fn normalize_relative_path(path: &str) -> Result<PathBuf, String> {
    let path = Path::new(path.trim());
    if path.as_os_str().is_empty() {
        return Err("Project path is required.".to_string());
    }
    if path.is_absolute() {
        return Err("Project path must be relative to the workspace.".to_string());
    }
    let mut normalized = PathBuf::new();
    for component in path.components() {
        match component {
            Component::Normal(part) => normalized.push(part),
            Component::CurDir => {}
            _ => return Err("Project path cannot contain parent directory segments.".to_string()),
        }
    }
    if normalized.as_os_str().is_empty() {
        return Err("Project path is required.".to_string());
    }
    Ok(normalized)
}

fn ensure_creatable_dir(path: &Path) -> Result<(), String> {
    if path.exists() && !path.is_dir() {
        return Err("Target path exists and is not a directory.".to_string());
    }
    if path.is_dir() {
        let mut entries = fs::read_dir(path).map_err(|e| e.to_string())?;
        if entries.next().is_some() {
            return Err("Target directory is not empty. Choose another path.".to_string());
        }
    }
    Ok(())
}

fn display_workspace_path(workspace_root: &Path, path: &Path) -> String {
    path.strip_prefix(workspace_root)
        .unwrap_or(path)
        .to_string_lossy()
        .trim_start_matches('/')
        .to_string()
}

fn execute_step(
    step: &CommandStep,
    cwd: &Path,
    timeout_ms: u64,
) -> Result<ProjectCommandResult, String> {
    let started = Instant::now();
    let mut child = Command::new(step.program)
        .args(step.args)
        .current_dir(cwd)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("Failed to start {}: {e}", step.program))?;

    let stdout = child
        .stdout
        .take()
        .ok_or_else(|| "Failed to capture stdout.".to_string())?;
    let stderr = child
        .stderr
        .take()
        .ok_or_else(|| "Failed to capture stderr.".to_string())?;
    let stdout_handle = thread::spawn(move || read_limited(stdout));
    let stderr_handle = thread::spawn(move || read_limited(stderr));
    let timeout = Duration::from_millis(timeout_ms);
    let (exit_code, timed_out) = loop {
        if let Some(status) = child.try_wait().map_err(|e| e.to_string())? {
            break (status.code(), false);
        }
        if started.elapsed() >= timeout {
            let _ = child.kill();
            let _ = child.wait();
            break (None, true);
        }
        thread::sleep(Duration::from_millis(20));
    };
    let stdout = stdout_handle.join().unwrap_or_default();
    let stderr = stderr_handle.join().unwrap_or_default();
    let success = !timed_out && exit_code == Some(0);
    Ok(ProjectCommandResult {
        command: format!("{} {}", step.program, step.args.join(" "))
            .trim()
            .to_string(),
        cwd: cwd.display().to_string(),
        success,
        stdout,
        stderr,
        exit_code,
        duration_ms: started.elapsed().as_millis(),
        timed_out,
        diagnosis: String::new(),
    })
}

fn read_limited(mut reader: impl Read) -> String {
    let mut output = Vec::new();
    let mut buffer = [0_u8; 8192];
    let mut truncated = false;
    loop {
        let Ok(read) = reader.read(&mut buffer) else {
            break;
        };
        if read == 0 {
            break;
        }
        let remaining = MAX_OUTPUT_LENGTH.saturating_sub(output.len());
        if remaining == 0 {
            truncated = true;
            continue;
        }
        let take = remaining.min(read);
        output.extend_from_slice(&buffer[..take]);
        if take < read {
            truncated = true;
        }
    }
    let mut text = String::from_utf8_lossy(&output).to_string();
    if truncated {
        text.push_str("\n[output truncated]");
    }
    text
}

fn append_step_output(target: &mut String, value: &str) {
    if target.len() >= MAX_OUTPUT_LENGTH {
        return;
    }
    let remaining = MAX_OUTPUT_LENGTH - target.len();
    if value.len() <= remaining {
        target.push_str(value);
    } else {
        target.push_str(&value[..remaining]);
        target.push_str("\n[output truncated]");
    }
}

fn diagnose_failure(
    stack: ProjectStack,
    kind: &str,
    stdout: &str,
    stderr: &str,
    timed_out: bool,
) -> String {
    if timed_out {
        return "Command timed out. For dev servers this usually means the server started and kept running; stop it manually if needed.".to_string();
    }
    let combined = format!("{}\n{}", stdout.to_lowercase(), stderr.to_lowercase());
    if combined.contains("command not found") || combined.contains("no such file or directory") {
        return match stack {
            ProjectStack::PythonCli | ProjectStack::PythonResearch | ProjectStack::StudyNotes | ProjectStack::ResearchWorkspace => {
                "Required runtime is missing or not on PATH. Install Python 3 and retry.".to_string()
            }
            ProjectStack::CppCmake => {
                "Required C++ toolchain or CMake is missing. Install CMake and a compiler, then retry.".to_string()
            }
            ProjectStack::Rust => {
                "Cargo is missing or not on PATH. Install Rust toolchain, then retry.".to_string()
            }
            ProjectStack::TypeScriptReact | ProjectStack::TauriApp => {
                "Node/npm dependencies may be missing. Run npm install in the project folder, then retry.".to_string()
            }
        };
    }
    if combined.contains("cannot find module") || combined.contains("vite: not found") {
        return "Node dependencies are missing. Run npm install in the project folder, then retry."
            .to_string();
    }
    if matches!(stack, ProjectStack::CppCmake)
        && kind != "build"
        && combined.contains("no tests were found")
    {
        return "Build the CMake project before running tests.".to_string();
    }
    if combined.contains("failed") || combined.contains("error") {
        return "Command failed. Check stderr above; the next agent step should inspect the failing file and propose a repair.".to_string();
    }
    String::new()
}

