use serde::{Deserialize, Serialize};
use std::fs;
use std::io::Read;
use std::path::{Component, Path, PathBuf};
use std::process::{Command, Stdio};
use std::thread;
use std::time::{Duration, Instant};

const DEFAULT_TIMEOUT_MS: u64 = 20_000;
const RUN_TIMEOUT_MS: u64 = 8_000;
const MAX_TIMEOUT_MS: u64 = 60_000;
const MAX_OUTPUT_LENGTH: usize = 100_000;

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProjectStackSummary {
    pub id: String,
    pub name: String,
    pub description: String,
    pub commands: Vec<ProjectCommandSpec>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProjectCommandSpec {
    pub kind: String,
    pub label: String,
    pub command: String,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CreateProjectRequest {
    pub name: String,
    pub stack: String,
    pub path: Option<String>,
    pub description: Option<String>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CreatedProject {
    pub name: String,
    pub stack: String,
    pub path: String,
    pub absolute_path: String,
    pub files: Vec<String>,
    pub commands: Vec<ProjectCommandSpec>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RunProjectCommandRequest {
    pub path: String,
    pub stack: String,
    pub command_kind: String,
    pub timeout_ms: Option<u64>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProjectCommandResult {
    pub command: String,
    pub cwd: String,
    pub success: bool,
    pub stdout: String,
    pub stderr: String,
    pub exit_code: Option<i32>,
    pub duration_ms: u128,
    pub timed_out: bool,
    pub diagnosis: String,
}

#[derive(Debug, Clone, Copy)]
enum ProjectStack {
    PythonCli,
    PythonResearch,
    CppCmake,
    Rust,
    TypeScriptReact,
    TauriApp,
    StudyNotes,
    ResearchWorkspace,
}

#[derive(Debug)]
struct FileTemplate {
    path: &'static str,
    content: String,
}

#[derive(Debug)]
struct CommandStep {
    program: &'static str,
    args: &'static [&'static str],
}

pub fn list_project_stacks() -> Vec<ProjectStackSummary> {
    ProjectStack::all()
        .into_iter()
        .map(|stack| ProjectStackSummary {
            id: stack.id().to_string(),
            name: stack.name().to_string(),
            description: stack.description().to_string(),
            commands: stack.commands(),
        })
        .collect()
}

pub fn create_project(
    workspace_root: &Path,
    request: CreateProjectRequest,
) -> Result<CreatedProject, String> {
    let stack = ProjectStack::from_id(&request.stack)?;
    let name = normalize_project_name(&request.name)?;
    let relative_path = request
        .path
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .map(ToString::to_string)
        .unwrap_or_else(|| format!("projects/{name}"));
    let target = resolve_new_project_path(workspace_root, &relative_path)?;
    ensure_creatable_dir(&target)?;

    let description = request
        .description
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .unwrap_or("Generated by ino-agent project wizard.");
    let templates = stack.templates(&name, description);
    fs::create_dir_all(&target).map_err(|e| e.to_string())?;
    let mut files = Vec::new();

    for template in templates {
        let file_path = target.join(template.path);
        if let Some(parent) = file_path.parent() {
            fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        fs::write(&file_path, template.content).map_err(|e| e.to_string())?;
        files.push(template.path.to_string());
    }

    files.sort();
    Ok(CreatedProject {
        name,
        stack: stack.id().to_string(),
        path: display_workspace_path(workspace_root, &target),
        absolute_path: target.display().to_string(),
        files,
        commands: stack.commands(),
    })
}

pub fn run_project_command(
    workspace_root: &Path,
    request: RunProjectCommandRequest,
) -> Result<ProjectCommandResult, String> {
    let stack = ProjectStack::from_id(&request.stack)?;
    let cwd = resolve_existing_project_path(workspace_root, &request.path)?;
    let steps = stack.command_steps(&request.command_kind)?;
    let command_label = stack
        .commands()
        .into_iter()
        .find(|command| command.kind == request.command_kind)
        .map(|command| command.command)
        .unwrap_or_else(|| request.command_kind.clone());

    let timeout_ms = request
        .timeout_ms
        .unwrap_or_else(|| {
            if request.command_kind == "run" {
                RUN_TIMEOUT_MS
            } else {
                DEFAULT_TIMEOUT_MS
            }
        })
        .clamp(1, MAX_TIMEOUT_MS);
    let started = Instant::now();
    let mut stdout = String::new();
    let mut stderr = String::new();
    let mut exit_code = Some(0);
    let mut timed_out = false;

    for step in steps {
        let remaining = timeout_ms.saturating_sub(started.elapsed().as_millis() as u64);
        if remaining == 0 {
            timed_out = true;
            exit_code = None;
            break;
        }
        let result = execute_step(&step, &cwd, remaining)?;
        append_step_output(&mut stdout, "$ ");
        append_step_output(&mut stdout, step.program);
        for arg in step.args {
            append_step_output(&mut stdout, " ");
            append_step_output(&mut stdout, arg);
        }
        append_step_output(&mut stdout, "\n");
        append_step_output(&mut stdout, &result.stdout);
        append_step_output(&mut stderr, &result.stderr);
        exit_code = result.exit_code;
        timed_out = result.timed_out;
        if !result.success {
            let diagnosis =
                diagnose_failure(stack, &request.command_kind, &stdout, &stderr, timed_out);
            return Ok(ProjectCommandResult {
                command: command_label,
                cwd: display_workspace_path(workspace_root, &cwd),
                success: false,
                stdout,
                stderr,
                exit_code,
                duration_ms: started.elapsed().as_millis(),
                timed_out,
                diagnosis,
            });
        }
    }

    let diagnosis = diagnose_failure(stack, &request.command_kind, &stdout, &stderr, timed_out);
    Ok(ProjectCommandResult {
        command: command_label,
        cwd: display_workspace_path(workspace_root, &cwd),
        success: !timed_out && exit_code == Some(0),
        stdout,
        stderr,
        exit_code,
        duration_ms: started.elapsed().as_millis(),
        timed_out,
        diagnosis,
    })
}

